"""Generate strict wire types from Pydantic JSON schemas. Run from repository root."""

import argparse
import inspect
import json
from pathlib import Path

from pydantic import BaseModel

from app.schemas import models


def ts_type(schema: dict[str, object] | bool) -> str:
    if isinstance(schema, bool):
        return "unknown" if schema else "never"
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(item) for item in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts_type(item) for item in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema.get('items', {}))}>"
    if kind == "object":
        return f"Record<string, {ts_type(schema.get('additionalProperties', {}))}>"
    return {
        "string": "string",
        "number": "number",
        "integer": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def definitions() -> dict[str, dict[str, object]]:
    schemas: dict[str, dict[str, object]] = {}
    for name, cls in inspect.getmembers(models, inspect.isclass):
        if issubclass(cls, BaseModel) and cls.__module__ == models.__name__:
            schema = cls.model_json_schema(mode="serialization")
            schemas.update(schema.pop("$defs", {}))
            schemas[name] = schema
    return schemas


def generate() -> str:
    output = ["// Generated by backend/scripts/generate_types.py. Do not edit by hand.\n"]
    for name, schema in sorted(definitions().items()):
        if schema.get("type") == "object" and "properties" in schema:
            fields = [f"  {key}: {ts_type(field)};" for key, field in schema["properties"].items()]
            output.append(f"export interface {name} {{\n" + "\n".join(fields) + "\n}\n")
        else:
            output.append(f"export type {name} = {ts_type(schema)};\n")
    # Narrow the runtime-validated message and job pairings at compile time, too.
    text = "\n".join(output)
    text = text.replace("interface WebSocketStreamMessage", "interface WebSocketStreamMessageBase")
    text = text.replace("interface JobStatusResponse", "interface JobStatusResponseBase")
    text += """
export type WebSocketStreamMessage = Omit<
  WebSocketStreamMessageBase, "message_type" | "payload"
> & (
  | { message_type: "NEW_EVENT"; payload: UnifiedSocialEventEnriched }
  | { message_type: "CTI_ALERT"; payload: CampaignAlert }
  | { message_type: "SCENARIO_RESET"; payload: ScenarioSwitchResponse }
  | { message_type: "JOB_UPDATED"; payload: JobNotification }
);
type SuccessfulJob =
  | { job_type: "SCENARIO"; result: ScenarioSwitchResponse }
  | { job_type: "INJECT"; result: UnifiedSocialEventEnriched }
  | { job_type: "FORENSICS"; result: ForensicMediaReport }
  | { job_type: "EXPORT"; result: EvidenceDossierBundle };
export type JobStatusResponse = Omit<
  JobStatusResponseBase, "status" | "result" | "job_type" | "error_code"
> & (
  | ({ status: "SUCCEEDED"; error_code: null } & SuccessfulJob)
  | { status: "QUEUED" | "RUNNING"; job_type: JobStatusResponseBase["job_type"];
      result: null; error_code: null }
  | { status: "FAILED"; job_type: JobStatusResponseBase["job_type"];
      result: null; error_code: string }
);
"""
    return text


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[2] / "frontend/src/types/chakravyuh.ts"
    result = generate()
    schema_target = target.with_name("schema.json")
    schema_result = (
        json.dumps({"$defs": definitions()}, ensure_ascii=False, sort_keys=True, indent=2) + "\n"
    )
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != result:
            raise SystemExit("TypeScript contracts are stale; regenerate them")
        if not schema_target.exists() or schema_target.read_text(encoding="utf-8") != schema_result:
            raise SystemExit("Runtime schemas are stale; regenerate them")
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(result, encoding="utf-8")
        schema_target.write_text(schema_result, encoding="utf-8")
